bool IsInvariant(std::uint32_t code) {
    if (code > 0x7F || code == 0x0A) return false;
    switch (code) {
        case 0x21: case 0x23: case 0x24: case 0x40:
        case 0x5B: case 0x5C: case 0x5D: case 0x5E:
        case 0x60: case 0x7B: case 0x7C: case 0x7D: case 0x7E: return false;
        default: return true;
    }
}

template<bool Ebcdic>
std::uint8_t NextPropertyCharacter(const char*& text) {
    for (;;) {
        auto value = static_cast<std::uint8_t>(*text++);
        if constexpr (Ebcdic) {
            if (value == 0x60 || value == 0x6D || value == 0x40 || value == 0x05 ||
                value == 0x15 || value == 0x25 || value == 0x0B || value == 0x0C || value == 0x0D) continue;
            if ((value >= 0xC1 && value <= 0xC9) || (value >= 0xD1 && value <= 0xD9) ||
                (value >= 0xE2 && value <= 0xE9)) value -= 0x40;
        } else {
            if (value == 0x2D || value == 0x5F || value == 0x20 || (value >= 0x09 && value <= 0x0D)) continue;
            if (value >= 0x41 && value <= 0x5A) value += 0x20;
        }
        return value;
    }
}

template<bool Ebcdic>
std::int32_t ComparePropertyNames(const char* first, const char* second) {
    for (;;) {
        const auto left = NextPropertyCharacter<Ebcdic>(first);
        const auto right = NextPropertyCharacter<Ebcdic>(second);
        if (left != right) return static_cast<std::int32_t>(left) - right;
        if (left == 0) return 0;
    }
}

std::int32_t EbcdicRank(std::uint8_t value) {
    if (value == 0) return 0;
    const auto ascii = AsciiFromEbcdic[value];
    return ascii != 0 && IsInvariant(ascii) ? ascii : -static_cast<std::int32_t>(value);
}

